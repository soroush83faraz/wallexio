"""Render gold/REPORT.md from the report JSON only (every number shown comes from report.json)."""
from __future__ import annotations

from typing import Any, Mapping, Sequence


def pct(x: float | None, signed: bool = True) -> str:
    if x is None:
        return "n/a"
    return f"{x * 100:+.2f}%" if signed else f"{x * 100:.2f}%"


def num(x: float | None, nd: int = 2) -> str:
    return "n/a" if x is None else f"{x:,.{nd}f}"


def _table(head: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


RUN_ORDER = ("V0", "V1", "V2", "V3", "V4", "S1", "S2", "S3", "S4")


def ordered(runs: Mapping[str, Any]) -> list[tuple[str, Any]]:
    """Runs in their pre-registered order (the JSON stores them sorted by key)."""
    keys = [k for k in RUN_ORDER if k in runs] + sorted(k for k in runs if k not in RUN_ORDER)
    return [(k, runs[k]) for k in keys]


def verdict(rep: Mapping[str, Any]) -> list[str]:
    v0 = rep["variants"]["V0"]
    bh, bh25 = rep["buy_and_hold"]["100pct"], rep["buy_and_hold"]["25pct"]
    t = v0["target"]
    met = "MET" if t["met"] else "NOT MET"
    lines = [
        f"**Target ~3 %/month: {met}.** Over {num(v0['days'], 1)} days ({rep['windows']['eval_start_utc']} to "
        f"{rep['windows']['eval_end_utc']} UTC) the pre-registered strategy (V0) turned "
        f"{num(v0['start_equity'])} USDT into {num(v0['final_equity'])} USDT: {pct(v0['total_return'])} in total, "
        f"a geometric average of {pct(v0['geo_avg_monthly_return'])} per month, against the 3.00 % target. "
        f"{t['complete_months_at_or_above_target']} of {t['complete_months']} complete months reached 3 %. "
        f"It made {v0['trades']} trades; max drawdown {pct(v0['max_drawdown'], False)}.",
        "",
        f"Buy-and-hold PAXG over the same window: {pct(bh['total_return'])} fully invested "
        f"({pct(bh['geo_avg_monthly_return'])}/month, max drawdown {pct(bh['max_drawdown'], False)}), "
        f"{pct(bh25['total_return'])} with 25 % of equity (the strategy's maximum position under the repo's caps). "
        f"PAXG itself moved {pct(bh['paxg_move'])} from the first evaluation open to the last close.",
    ]
    best = max(rep["variants"].items(), key=lambda kv: kv[1]["geo_avg_monthly_return"] or -1)
    lines += ["", f"No variant reached the target: the best of all {len(rep['variants'])} runs ({best[0]}) averaged "
              f"{pct(best[1]['geo_avg_monthly_return'])}/month." if not any(
                  r["target"]["met"] for r in rep["variants"].values()) else
              "At least one variant met the target; see the table (variants are not selected, V0 is the result)."]
    return lines


def render_markdown(rep: Mapping[str, Any]) -> str:
    v = rep["variants"]
    v0 = v["V0"]
    bh, bh25 = rep["buy_and_hold"]["100pct"], rep["buy_and_hold"]["25pct"]
    L: list[str] = ["# Gold backtest report (wallexio)", "",
                    "Generated by `python -m wallexbot gold-backtest` from the committed files in `gold/data/`; "
                    "every number below is read from `gold/report.json`. Strategy, parameters, windows, variants "
                    "and the success criterion were written down before any run: [README.md](README.md). "
                    "A backtest is not live trading, and nothing here promises profit.", "", "## Verdict", ""]
    L += verdict(rep)
    d = rep["data"]
    L += ["", "## Setup", "",
          f"- Bars: {d['bars']}, {d['n_bars']} bars, {d['first_utc']} to {d['last_close_utc']} UTC "
          f"(fetched {d['fetched_at_utc']}). Warm-up (no trades) until {rep['windows']['eval_start_utc']} UTC.",
          f"- Traded market: Wallex {rep['symbol_traded']} (price precision {rep['symbol_rules']['price_precision']}, "
          f"amount precision {rep['symbol_rules']['amount_precision']}); prices from Binance PAXGUSDT (basis below).",
          f"- Engine `{rep['engine_version']}` (next-bar-open fills, gap-aware stops, stop-first on ambiguous bars), "
          f"strategy `{rep['strategy_version']}`, starting equity {num(rep['initial_equity'])} USDT, long-only spot.",
          "- Costs (V0): taker fee 0.2 % per side, half-spread 7.5 bps, impact 0.2 x order / previous-bar notional "
          "(Binance volume, so near zero) capped at 50 bps.",
          "- Risk (repo default_config.yaml): " + ", ".join(f"{k} {val}" for k, val in rep["risk_config"].items()),
          "", "## V0 headline", ""]
    L += _table(["metric", "V0", "buy & hold 100 %", "buy & hold 25 %"], [
        ["total return", pct(v0["total_return"]), pct(bh["total_return"]), pct(bh25["total_return"])],
        ["geometric avg / month", pct(v0["geo_avg_monthly_return"]), pct(bh["geo_avg_monthly_return"]),
         pct(bh25["geo_avg_monthly_return"])],
        ["arithmetic mean of complete months", pct(v0["target"]["arith_mean_complete_months"]),
         pct(bh["target"]["arith_mean_complete_months"]), pct(bh25["target"]["arith_mean_complete_months"])],
        ["complete months >= 3 %", f"{v0['target']['complete_months_at_or_above_target']} / {v0['target']['complete_months']}",
         f"{bh['target']['complete_months_at_or_above_target']} / {bh['target']['complete_months']}",
         f"{bh25['target']['complete_months_at_or_above_target']} / {bh25['target']['complete_months']}"],
        ["max drawdown", pct(v0["max_drawdown"], False), pct(bh["max_drawdown"], False), pct(bh25["max_drawdown"], False)],
        ["final equity (USDT)", num(v0["final_equity"]), num(bh["final_equity"]), num(bh25["final_equity"])],
        ["trades", str(v0["trades"]), "1", "1"],
        ["win rate", pct(v0["win_rate"], False), "", ""],
        ["profit factor", num(v0["profit_factor"]), "", ""],
        ["fees + spread + impact paid (USDT)", f"{num(v0['total_costs'])} ({num(v0['fees'])} + {num(v0['spread_cost'])} + "
         f"{num(v0['impact_cost'])})", num(bh["costs"]), num(bh25["costs"])],
        ["time in a position", pct(v0["exposure_time"], False), "100.00%", "100.00%"],
        ["avg position / equity when in", pct(v0["avg_position_pct_when_in"], False), "100.00%", "25.00%"],
    ])
    L += ["", "## Per month", "",
          "Return of each calendar month, from the previous month-end equity (marked to market). The last row "
          "is a partial month.", ""]
    bhm = {r["month"]: r for r in bh["monthly"]}
    bh25m = {r["month"]: r for r in bh25["monthly"]}
    s1m = {r["month"]: r for r in v["S1"]["monthly"]}
    L += _table(["month", "V0", "V0 fees x2 (S1)", "B&H 100 %", "B&H 25 %", "V0 trades closed", "complete"], [
        [r["month"], pct(r["return"]), pct(s1m[r["month"]]["return"]) if r["month"] in s1m else "n/a",
         pct(bhm[r["month"]]["return"]) if r["month"] in bhm else "n/a",
         pct(bh25m[r["month"]]["return"]) if r["month"] in bh25m else "n/a",
         str(r["trades_closed"]), "yes" if r["complete"] else "partial"] for r in v0["monthly"]])
    L += ["", "## V0 trades", ""]
    L += _table(["#", "entry (UTC)", "entry price", "qty PAXG", "notional", "initial stop", "exit (UTC)", "exit price",
                 "reason", "hours", "net P&L", "costs", "R"],
                [[str(i + 1), t["entry_utc"], t["entry_price"], t["qty"], num(t["notional"]), t["initial_stop"],
                  t["exit_utc"], num(t["exit_price"]), t["exit_reason"], str(t["bars_held"]), num(t["net_pnl"]),
                  num(t["costs"]), num(t["r_multiple"])] for i, t in enumerate(v0["trade_list"])])
    L += ["", "Engine events (V0): " + (", ".join(f"{k} x{n}" for k, n in v0["events"].items()) or "none") + ".",
          "", "## Every pre-registered run", "",
          "V1-V4 are the +/-20 % parameter neighbours, S1-S4 cost and structure stresses. All are reported; none "
          "is selected.", ""]
    L += _table(["id", "what", "total", "avg / month (geo)", "max DD", "trades", "win rate", "profit factor",
                 "costs USDT", "months >= 3 %", "target met"],
                [[k, r["label"], pct(r["total_return"]), pct(r["geo_avg_monthly_return"]), pct(r["max_drawdown"], False),
                  str(r["trades"]), pct(r["win_rate"], False), num(r["profit_factor"]), num(r["total_costs"]),
                  f"{r['target']['complete_months_at_or_above_target']} / {r['target']['complete_months']}",
                  "yes" if r["target"]["met"] else "no"] for k, r in ordered(v)])
    if "trade_list" in v.get("S3", {}):
        L += ["", "S3 (caps lifted) trades: " + "; ".join(
            f"{t['entry_utc']} -> {t['exit_utc']} {num(t['net_pnl'])} USDT" for t in v["S3"]["trade_list"]) + "."]
    L += _wallex(rep)
    L += ["", "## Shadow", "",
          "The shadow replays through the bot / OMS / risk engine / ShadowBroker path (the pre-registered last 30 "
          "days, and the whole evaluation window to exercise fills) and their comparison with this backtest are in "
          "[SHADOW.md](SHADOW.md) (`python -m wallexbot gold-shadow`).", "",
          "## Limitations", "",
          "- One market, one ~6.7-month window, a handful of trades: far too small a sample to estimate an edge. "
          "The result mostly reflects this window's gold regime (see buy-and-hold); a trend rule earns when gold "
          "trends and loses in chop, so a different window can give a very different number.",
          "- Prices are Binance PAXGUSDT. The Wallex PAXGUSDT market is thin, wide and trades at a varying discount "
          "to Binance (table above), so fills there would differ; XAUTUSDT on Wallex is the realistic venue.",
          "- The cost model is the repo's assumption set (0.2 % taker fee unverified for our tier, 7.5 bps "
          "half-spread, a volume impact proxy). No Wallex depth history exists for gold beyond the snapshots above.",
          "- 1h bars: nothing is known inside a bar; stops fill at the stop (or the open on a gap), and the stop "
          "is assumed hit first when one bar touches both. The shadow replay checks stops on 5m prices instead.",
          "- The repo's 25 % max position caps what any strategy can earn here: a fully invested trade gains a "
          "quarter of gold's move. S3 shows the same signals without the caps.",
          "", "## Reproduce", "", "```bash",
          "python -m wallexbot gold-backtest            # rewrites gold/report.json and gold/REPORT.md (deterministic)",
          "python -m wallexbot gold-shadow              # replays through the bot path -> runs/, gold/SHADOW.md",
          "python -m wallexbot gold-fetch               # re-download gold/data/ (network; changes the inputs)",
          "```", ""]
    return "\n".join(L)


def _wallex(rep: Mapping[str, Any]) -> list[str]:
    w = rep["wallex"]
    L = ["", "## Wallex reality check", "",
         "Order-book snapshots (`gold/data/wallex_depth.jsonl`) and Wallex 1h candles vs Binance PAXGUSDT closes "
         "(positive = Wallex above). A market BUY/SELL cost is the VWAP distance from mid when walking the "
         "visible book.", ""]
    rows = []
    for sym, dd in sorted(w["depth"].items()):
        mk = w["markets"].get(sym, {})
        c250, c1000 = dd["vwap_cost_vs_mid_bps"]["250"], dd["vwap_cost_vs_mid_bps"]["1000"]
        rows.append([sym, num(dd["median_half_spread_bps"]), num(dd["max_half_spread_bps"]),
                     f"{num(c250['BUY'])} / {num(c250['SELL'])}", f"{num(c1000['BUY'])} / {num(c1000['SELL'])}",
                     num(float(mk["quote_volume_24h"]), 0) if mk.get("quote_volume_24h") else "n/a", str(dd["snapshots"])])
    L += _table(["market", "half-spread bps (median)", "half-spread bps (max)", "250 USDT buy / sell bps",
                 "1000 USDT buy / sell bps", "24h volume USDT", "snapshots"], rows)
    L += [""]
    rows = []
    for sym, b in sorted(w["basis_vs_binance_paxg"].items()):
        t = b["traded_hours"]
        rows.append([sym, str(b["common_hours"]), pct(b["zero_volume_hour_share"], False), num(t["median_bps"], 1),
                     num(t["mean_abs_bps"], 1), f"{num(t['p05_bps'], 1)} / {num(t['p95_bps'], 1)}",
                     num(b["median_hourly_notional_usdt"], 0)])
    L += _table(["market", "common hours", "hours with no trade", "median basis bps (traded hours)",
                 "mean abs basis bps", "p05 / p95 bps", "median hourly notional USDT"], rows)
    return L
